"""Qwen-Drive-compatible text API backed by a persistent vLLM engine."""
import json
import time
from pathlib import Path
from types import SimpleNamespace
from lead.inference.qwendrive_intent_client import QwenDriveInputMismatchError


ARCHITECTURE = 'P7QwenDriveForConditionalGeneration'


def collapse_image_tokens(tokens, image_token_id):
    """Keep the official ChatML IDs, with one image placeholder per image span."""
    result = []
    for token in tokens:
        if token != image_token_id or not result or result[-1] != image_token_id:
            result.append(token)
    return result


class VLLMQwenDrive:
    def __init__(self, model_dir, *, gpu_memory_utilization=0.5, max_model_len=4096,
                 enforce_eager=False):
        from importlib.metadata import entry_points
        if not any(point.name == 'lead_qwendrive' for point in entry_points(group='vllm.general_plugins')):
            raise RuntimeError('Install the P7 plugin in this environment: '
                               'python -m pip install --no-deps -e scripts/p7/vllm_plugin')
        from transformers import AutoTokenizer
        from vllm import LLM
        from lead.inference.qwendrive_vllm_inputs import official_processor

        config = json.loads((Path(model_dir) / 'config.json').read_text())
        if config.get('model_type') != 'qwen3_5' or 'p7_qwendrive_config' not in config:
            raise ValueError('Use the standalone VLM directory created by prepare_qwendrive_vllm.py')
        tokenizer = AutoTokenizer.from_pretrained(model_dir)
        self.processor = official_processor(tokenizer, config['p7_qwendrive_config'])
        self.last_metrics = None
        self.llm = LLM(
            model=str(model_dir), tokenizer=str(model_dir), dtype='bfloat16',
            hf_overrides={'architectures': [ARCHITECTURE]},
            gpu_memory_utilization=gpu_memory_utilization, max_model_len=max_model_len,
            max_num_seqs=1, max_num_batched_tokens=max_model_len,
            limit_mm_per_prompt={'image': 3, 'video': 0},
            mm_processor_kwargs={'max_pixels': config['p7_qwendrive_config']['current_image_pixels']},
            enable_prefix_caching=False, enforce_eager=enforce_eager, seed=3407,
        )

    def generate_text(self, images, question, *, max_new_tokens):
        from vllm import SamplingParams
        from qwen_drive.modeling_qwen_drive import VQA_DECODE_DEFAULTS

        start = time.monotonic()
        reference = self.processor.encode_vqa(images, question, device='cpu')
        reference_ids = reference['input_ids'][0].tolist()
        prompt = collapse_image_tokens(reference_ids, self.processor.image_token_id)
        # Pixel tensors are regenerated by the plugin with the SAME official
        # processor. They are not sent through vLLM's default image resizing.
        del reference
        prepared = time.monotonic()
        defaults = dict(VQA_DECODE_DEFAULTS)
        params = SamplingParams(
            temperature=defaults['temperature'], top_k=defaults['top_k'], top_p=defaults['top_p'],
            repetition_penalty=defaults['repetition_penalty'], presence_penalty=defaults['presence_penalty'],
            seed=defaults['seed'], max_tokens=max_new_tokens, skip_special_tokens=True,
        )
        output = self.llm.generate(
            [{'prompt_token_ids': prompt, 'multi_modal_data': {'image': images}}],
            params, use_tqdm=False,
        )[0]
        if list(output.prompt_token_ids or []) != reference_ids:
            raise QwenDriveInputMismatchError('vLLM prompt token expansion differs from official Qwen-Drive; '
                               'stopping this request instead of evaluating mismatched inputs')
        answer = output.outputs[0]
        self.last_metrics = {
            'backend': 'vllm', 'preprocess_seconds': prepared - start,
            'engine_seconds': time.monotonic() - prepared, 'tokens': len(answer.token_ids),
            'prompt_tokens': len(reference_ids), 'prompt_ids_exact': True,
            'finish_reason': answer.finish_reason, 'hit_limit': answer.finish_reason == 'length',
        }
        return SimpleNamespace(text=answer.text.split('</think>')[-1].strip())
